/* Browser checks for the actual birthday gift flow. Run with Playwright installed. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const path=require('node:path');

(async()=>{
  const browser=await chromium.launch({headless:true});
  const screenshots=path.resolve('browser-results');
  await fs.mkdir(screenshots,{recursive:true});
  const errors=[];
  const context=await browser.newContext({viewport:{width:393,height:852},isMobile:true,hasTouch:true,deviceScaleFactor:1,acceptDownloads:true,colorScheme:'light'});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8080/',{waitUntil:'networkidle'});
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('[data-change="GOOGL"]').filter({hasText:/Fetching/}).waitFor({state:'hidden'});
  for(const width of [320,375,393,430,768,1440]){
    await page.setViewportSize({width,height:852});
    const layout=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,taps:[...document.querySelectorAll('button')].filter(b=>b.getBoundingClientRect().width>0).map(b=>({text:b.textContent.trim()||b.getAttribute('aria-label'),height:b.getBoundingClientRect().height}))}));
    assert.ok(layout.scroll<=layout.width,`Horizontal overflow at ${width}: ${layout.scroll}`);
    assert.ok(layout.taps.every(b=>b.height>=44),`Undersized touch target at ${width}: ${JSON.stringify(layout.taps)}`);
    console.log(`PASS layout and tap targets at ${width}px`);
  }
  await page.setViewportSize({width:393,height:852});
  await page.screenshot({path:path.join(screenshots,'phone-home.png'),fullPage:true});
  await page.locator('[data-choose="GOOGL"]').tap();
  await page.locator('#ceremony').waitFor({state:'visible'});
  await page.waitForTimeout(1500);
  await page.screenshot({path:path.join(screenshots,'phone-handoff.png')});
  await page.locator('#receipt').waitFor({state:'visible'});
  assert.equal(await page.locator('#receipt-company').textContent(),'Google');
  assert.match(await page.locator('#receipt-ticker').textContent(),/GOOGL/);
  assert.ok(await page.locator('.receipt-terms').textContent().then(t=>t.includes('whichever comes later')));
  const marketPrice=await page.locator('[data-price="GOOGL"]').textContent();
  if(!marketPrice.startsWith('—'))assert.equal((await page.locator('#receipt-price').textContent()).replace(' USD',''),marketPrice.replace('USD',''));
  assert.ok(await page.evaluate(()=>document.querySelector('#reveal').scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(screenshots,'phone-certificate.png')});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').tap();
  const download=await downloadPromise;
  await download.saveAs(path.join(screenshots,download.suggestedFilename()));
  assert.match(await fs.readFile(await download.path(),'utf8'),/Neelesh Bhakth/);
  console.log('PASS Google handoff, certificate, quoted value, and download');
  await page.locator('#choose-again').tap();
  await page.locator('[data-choose="META"]').tap();
  await page.locator('#receipt').waitFor({state:'visible'});
  assert.equal(await page.locator('#receipt-company').textContent(),'Meta');
  await page.locator('#close-reveal').tap();
  await page.reload({waitUntil:'networkidle'});
  await page.locator('#view-saved').tap();
  assert.equal(await page.locator('#receipt-company').textContent(),'Meta');
  assert.ok(await page.locator('#receipt').isVisible());
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.querySelector('#reveal').open),false);
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'');
  console.log('PASS Meta choice, persistence, reopen, and keyboard dismissal');
  await page.locator('#theme').tap();
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(screenshots,'phone-dark.png'),fullPage:true});
  await page.locator('#theme').tap();
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(screenshots,'desktop-home.png'),fullPage:true});
  const accessible=await page.locator('body').ariaSnapshot();
  await fs.writeFile(path.join(screenshots,'accessibility.txt'),accessible);
  const reduced=await browser.newContext({viewport:{width:375,height:812},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const reducedPage=await reduced.newPage();
  reducedPage.on('pageerror',e=>errors.push(e.message));
  await reducedPage.route('**/quotes.json',route=>route.fulfill({contentType:'application/json',body:'{"quotes":{}}'}));
  await reducedPage.goto('http://127.0.0.1:8080/',{waitUntil:'networkidle'});
  assert.equal(await reducedPage.locator('[data-change="META"]').textContent(),'Quote temporarily unavailable');
  await reducedPage.locator('[data-choose="META"]').tap();
  await reducedPage.locator('#receipt').waitFor({state:'visible',timeout:1000});
  assert.equal(await reducedPage.locator('#receipt-price').textContent(),'Quote unavailable');
  console.log('PASS reduced motion and missing quote fallback');
  assert.deepEqual(errors,[],'Browser JavaScript errors');
  console.log('PASS no browser JavaScript errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
